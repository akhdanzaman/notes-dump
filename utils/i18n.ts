import { AppLanguage } from '../types';

export const DEFAULT_APP_LANGUAGE: AppLanguage = 'id';

export const normalizeAppLanguage = (language?: AppLanguage): AppLanguage =>
  language === 'en' ? 'en' : DEFAULT_APP_LANGUAGE;

export const getAppLocale = (language?: AppLanguage): string =>
  normalizeAppLanguage(language) === 'en' ? 'en-US' : 'id-ID';

export const pickLanguage = <T>(
  language: AppLanguage | undefined,
  translations: { id: T; en: T },
): T => translations[normalizeAppLanguage(language)];

